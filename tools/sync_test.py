import unittest

import sync


class ParseProjectsTest(unittest.TestCase):
    def test_skips_dev_commented_and_generated(self):
        text = "\n".join([
            'module(name = "x")',
            'bazel_dep(name = "zlib", version = "1.3")',
            '# bazel_dep(name = "dropped", version = "1")',
            'bazel_dep(',
            '    name = "re2",',
            '    version = "2025-11-05.bcr.1",',
            ')',
            'bazel_dep(name = "rules_python", version = "2", dev_dependency = True)',
            sync.BEGIN,
            'bazel_dep(name = "nope", version = "1")',
            sync.END,
        ])
        self.assertEqual(
            sync.parse_projects(text),
            [("zlib", "1.3"), ("re2", "2025-11-05.bcr.1")],
        )


class GeneratedBlockTest(unittest.TestCase):
    def test_replace_is_idempotent(self):
        once = sync.replace_generated("a\n", "b\n")
        self.assertEqual(once, "a\n\n%s\nb\n%s\n" % (sync.BEGIN, sync.END))
        self.assertEqual(sync.replace_generated(once, "b\n"), once)
        self.assertEqual(sync.replace_generated(once, ""), "a\n")


class UndevTest(unittest.TestCase):
    def test_single_line(self):
        self.assertEqual(
            sync.undev('bazel_dep(name = "g", version = "1", dev_dependency = True)\n'),
            'bazel_dep(name = "g", version = "1")\n',
        )

    def test_multi_line(self):
        self.assertEqual(
            sync.undev('x = use_extension(\n    "@a//:b.bzl",\n    "c",\n    dev_dependency = True,\n)\n'),
            'x = use_extension(\n    "@a//:b.bzl",\n    "c",\n)\n',
        )

    def test_no_dev_deps_no_patch(self):
        self.assertIsNone(sync.make_patch('bazel_dep(name = "g", version = "1")\n'))

    def test_patch_headers(self):
        patch = sync.make_patch('bazel_dep(name = "g", version = "1", dev_dependency = True)\n')
        self.assertTrue(patch.startswith("--- a/MODULE.bazel\n+++ b/MODULE.bazel\n"))


class QueryTest(unittest.TestCase):
    def test_parse_ignores_noise(self):
        out = "\n".join([
            "\x1b[32mINFO: \x1b[mInvocation ID: 123",
            "cc_test rule @re2//:set_test",
            "alias rule @zlib//:z",
            "cc_library rule @abseil-cpp//absl/strings:strings",
            "source file @zlib//:zlib.h",
        ])
        self.assertEqual(sync.parse_query(out), {
            "re2": [("cc_test", "@re2//:set_test")],
            "zlib": [("alias", "@zlib//:z")],
            "abseil-cpp": [("cc_library", "@abseil-cpp//absl/strings:strings")],
        })


class ExclusionsTest(unittest.TestCase):
    def test_parse_requires_reason(self):
        self.assertEqual(sync.parse_exclusions("# c\n\n@a//:b needs tzdata\n"),
                         [("@a//:b", "needs tzdata")])
        with self.assertRaises(ValueError):
            sync.parse_exclusions("@a//:b\n")

    def test_patterns(self):
        pats = ["@a//x/...", "@b//...", "@c//:t"]
        self.assertTrue(sync.is_excluded("@a//x:t", pats))
        self.assertTrue(sync.is_excluded("@a//x/y:t", pats))
        self.assertFalse(sync.is_excluded("@a//xy:t", pats))
        self.assertTrue(sync.is_excluded("@b//any:t", pats))
        self.assertTrue(sync.is_excluded("@c//:t", pats))
        self.assertFalse(sync.is_excluded("@c//:t2", pats))


class RenderBuildTest(unittest.TestCase):
    def test_aliases_and_suite(self):
        text = sync.render_build("m", [
            ("cc_library", "@m//:lib"),
            ("cc_library", "@m//a/b:lib"),
            ("cc_library", "@m//a_b:lib"),
            ("cc_library", "@m//:tests"),
            ("cc_test", "@m//a:t_test"),
            ("cc_test", "@m//a:skip_test"),
            ("test_suite", "@m//a:all_tests"),
        ], ["@m//a:skip_test"])
        self.assertIn('name = "lib",\n    actual = "@m//:lib"', text)
        self.assertIn('name = "a_b__lib",\n    actual = "@m//a/b:lib"', text)
        self.assertIn('name = "a_b__lib_2",\n    actual = "@m//a_b:lib"', text)
        self.assertIn('name = "tests_2",\n    actual = "@m//:tests"', text)
        self.assertIn('"@m//a:t_test",', text)
        self.assertNotIn("skip_test", text)
        self.assertNotIn("all_tests", text)
        self.assertTrue(text.startswith("# Generated by tools/sync.py from @m."))


if __name__ == "__main__":
    unittest.main()
