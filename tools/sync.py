#!/usr/bin/env python3
"""Regenerates projects.json and //<module>:BUILD.bazel from projects.txt.

    python3 tools/sync.py           # at the BCR commit projects.json records
    python3 tools/sync.py --update  # at the BCR's current HEAD

It keeps a sparse, shallow clone of the Bazel Central Registry
(metadata.json, source.json and MODULE.bazel files only) in
~/.cache/bazel-matrix/bcr, checked out at the recorded commit, so re-running
it changes nothing. For each project in projects.txt it picks the pinned
version, or else the latest stable, non-yanked version whose
bazel_compatibility admits the default inner Bazel; records its source
(archive, integrity, strip_prefix, patches and overlay, as bcr.bazel.build
URLs with their integrity) in projects.json; and writes //<module>:BUILD.bazel.
Generated packages of projects no longer listed are deleted.
"""

import argparse
import base64
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BCR_GIT = "https://github.com/bazelbuild/bazel-central-registry"
BCR_URL = "https://bcr.bazel.build"
CACHE = os.path.join(os.path.expanduser("~"), ".cache", "bazel-matrix", "bcr")
GENERATED = "# Generated by tools/sync.py"

# ---------------------------------------------------------------------------
# projects.txt


def parse_projects_txt(text):
    """[{name, version, exclude: [(pattern, reason)], flags: [(flag, reason)],
    bazel: (version, reason) or None}] from projects.txt.

    A project line is `module` or `module@version`. Indented lines below it
    are `-//pattern reason`, `--flag reason` or `bazel <version> reason`;
    every one needs a reason.
    """
    projects, errors = [], []
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if not raw[0].isspace():
            name, _, version = line.partition("@")
            if not re.fullmatch(r"[a-z][a-z0-9._-]*", name) or " " in line:
                errors.append("line %d: bad project %r" % (n, line))
                continue
            if any(p["name"] == name for p in projects):
                errors.append("line %d: %s listed twice" % (n, name))
            projects.append({"name": name, "version": version or None,
                             "exclude": [], "flags": [], "bazel": None})
            continue
        if not projects:
            errors.append("line %d: indented line before any project" % n)
            continue
        parts = line.split(None, 2 if line.startswith("bazel ") else 1)
        p = projects[-1]
        if parts[0] == "bazel" and len(parts) == 3:
            p["bazel"] = (parts[1], parts[2])
        elif len(parts) < 2:
            errors.append("line %d: %r needs a reason" % (n, line))
        elif re.fullmatch(r"-(//|@)\S*", parts[0]) and "*" not in parts[0]:
            p["exclude"].append((parts[0][1:], parts[1]))
        elif parts[0].startswith("--"):
            p["flags"].append((parts[0], parts[1]))
        else:
            errors.append("line %d: expected -//pattern, --flag or bazel <version>: %r" % (n, line))
    if errors:
        raise ValueError("projects.txt:\n  " + "\n  ".join(errors))
    return projects


# ---------------------------------------------------------------------------
# Version selection (after tools/add.py on the scale-tooling branch).


def _ident(s):
    return (0, int(s), "") if s.isdigit() else (1, 0, s)


def version_key(v):
    """Sort key following Bazel's module version ordering."""
    v = v.split("+", 1)[0]
    rel, _, pre = v.partition("-")
    relk = tuple(_ident(x) for x in rel.split(".")) if rel else ()
    prek = (1,) if not pre else (0, tuple(_ident(x) for x in pre.split(".")))
    return ((1,) if not rel else (0,), relk, prek)


def is_stable(v):
    return "-" not in v.split("+", 1)[0]


def _num(v):
    return tuple(int(x) for x in re.findall(r"\d+", v)[:3])


def bazel_compatible(constraints, bazel):
    """Whether bazel_compatibility constraints (">=7.2.1", "-9.0.0") admit bazel."""
    b = _num(bazel)
    for c in constraints:
        m = re.match(r"^(>=|<=|>|<|-)\s*(\S+)$", c.strip())
        if not m:
            continue
        op, v = m.group(1), _num(m.group(2))
        if not {">=": b >= v, "<=": b <= v, ">": b > v, "<": b < v, "-": b != v}[op]:
            return False
    return True


def bazel_compatibility(module_text):
    """The bazel_compatibility list of a MODULE.bazel's module() call."""
    text = re.sub(r"#[^\n]*", "", module_text)
    m = re.search(r"\bmodule\s*\((.*?)\)", text, re.S)
    if not m:
        return []
    c = re.search(r"bazel_compatibility\s*=\s*\[([^\]]*)\]", m.group(1))
    return re.findall(r"[\"']([^\"']*)[\"']", c.group(1)) if c else []


def pick(metadata, module_text_for, bazel):
    """(version, None) for a module's latest usable version, or (None, why)."""
    if metadata.get("deprecated"):
        return None, "deprecated"
    yanked = metadata.get("yanked_versions") or {}
    versions = sorted((v for v in metadata.get("versions", []) if v not in yanked), key=version_key)
    if not versions:
        return None, "all versions yanked"
    # Date versions like re2's 2025-11-05 parse as prereleases; a module
    # with nothing else uses its latest.
    stable = [v for v in versions if is_stable(v)] or versions
    latest = stable[-1]
    text = module_text_for(latest)
    if text is None:
        return None, "no MODULE.bazel for " + latest
    if not bazel_compatible(bazel_compatibility(text), bazel):
        return None, "%s: bazel_compatibility %s excludes Bazel %s" % (
            latest, bazel_compatibility(text), bazel)
    return latest, None


# ---------------------------------------------------------------------------
# projects.json and BUILD files.


def integrity(data):
    return "sha256-" + base64.b64encode(hashlib.sha256(data).digest()).decode()


def source_entry(name, version, source, module_file):
    """projects.json's `source` for a BCR source.json and MODULE.bazel (bytes).

    Like Bazel fetching from a registry, the registry's MODULE.bazel replaces
    the source's: a .bcr.N version may change only that file.
    """
    kind = source.get("type", "archive")
    if kind != "archive":
        raise ValueError("%s@%s: %s sources aren't supported yet" % (name, version, kind))
    base = "%s/modules/%s/%s" % (BCR_URL, name, version)
    entry = {
        "urls": [source["url"]] + list(source.get("mirror_urls", [])),
        "integrity": source["integrity"],
    }
    for key in ("strip_prefix", "archive_type"):
        if source.get(key):
            entry[key] = source[key]
    if source.get("patches"):
        entry["patches"] = [{"url": "%s/patches/%s" % (base, p), "integrity": i}
                            for p, i in source["patches"].items()]
        entry["patch_strip"] = int(source.get("patch_strip", 0))
    if source.get("overlay"):
        entry["overlay"] = [{"path": p, "url": "%s/overlay/%s" % (base, p), "integrity": i}
                            for p, i in sorted(source["overlay"].items())]
    entry["module_file"] = {"url": base + "/MODULE.bazel", "integrity": integrity(module_file)}
    return entry


def targets(project):
    return ["//..."] + ["-" + p for p, _ in project["exclude"]]


def _q(s):
    return json.dumps(s)


def render_build(project):
    out = [GENERATED + " from projects.txt. Do not edit; see README.md.\n\n",
           'load("//tools:project.bzl", "project")\n\n',
           "project(\n",
           "    name = %s,\n" % _q(project["name"]),
           "    targets = [\n",
           '        "//...",\n']
    for pattern, reason in project["exclude"]:
        out.append("        # %s\n        %s,\n" % (reason, _q("-" + pattern)))
    out.append("    ],\n")
    if project["flags"]:
        out.append("    flags = [\n")
        for flag, reason in project["flags"]:
            out.append("        # %s\n        %s,\n" % (reason, _q(flag)))
        out.append("    ],\n")
    if project["bazel"]:
        out.append("    # %s\n    bazel_version = %s,\n" % (project["bazel"][1], _q(project["bazel"][0])))
    out.append(")\n")
    return "".join(out)


def render_json(commit, entries):
    return json.dumps({"bcr_commit": commit, "projects": entries}, indent=2) + "\n"


# ---------------------------------------------------------------------------
# Side effects.


def read(path):
    with open(os.path.join(ROOT, path)) as f:
        return f.read()


def write(path, text):
    path = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)


def is_generated(path):
    try:
        with open(path) as f:
            return f.readline().startswith(GENERATED)
    except OSError:
        return False


def checkout_bcr(commit, path=CACHE):
    """Checks out the sparse BCR clone at commit (or HEAD if None); returns the commit."""
    git = ["git", "-C", path]
    if not os.path.isdir(os.path.join(path, ".git")):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        subprocess.run(["git", "clone", "-q", "--depth=1", "--filter=blob:none",
                        "--no-checkout", BCR_GIT, path], check=True)
    subprocess.run(git + ["sparse-checkout", "set", "--no-cone", "/modules/*/metadata.json",
                          "/modules/*/*/source.json", "/modules/*/*/MODULE.bazel"], check=True)
    have = subprocess.run(git + ["rev-parse", "-q", "--verify", "HEAD"],
                          stdout=subprocess.PIPE, text=True).stdout.strip()
    if not commit or have != commit:
        subprocess.run(git + ["fetch", "-q", "--depth=1", "origin", commit or "HEAD"], check=True)
        subprocess.run(git + ["checkout", "-q", "--force", "FETCH_HEAD"], check=True)
    return subprocess.run(git + ["rev-parse", "HEAD"], stdout=subprocess.PIPE, text=True,
                          check=True).stdout.strip()


def _read_json(path):
    with open(path) as f:
        return json.load(f)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--update", action="store_true", help="move to the BCR's current HEAD")
    args = ap.parse_args()

    projects = parse_projects_txt(read("projects.txt"))
    old = {}
    if os.path.exists(os.path.join(ROOT, "projects.json")):
        old = json.loads(read("projects.json"))
    commit = checkout_bcr(None if args.update else old.get("bcr_commit"))
    modules = os.path.join(CACHE, "modules")
    bazel = read(".bazelversion").strip()

    entries, errors = [], []
    for p in projects:
        mdir = os.path.join(modules, p["name"])
        if not os.path.isfile(os.path.join(mdir, "metadata.json")):
            errors.append("%s: not in the BCR" % p["name"])
            continue
        version = p["version"]
        if not version:
            def text_for(v, mdir=mdir):
                path = os.path.join(mdir, v, "MODULE.bazel")
                return open(path, encoding="utf-8", errors="replace").read() if os.path.isfile(path) else None
            version, why = pick(_read_json(os.path.join(mdir, "metadata.json")), text_for,
                                p["bazel"][0] if p["bazel"] else bazel)
            if why:
                errors.append("%s: %s" % (p["name"], why))
                continue
        try:
            with open(os.path.join(mdir, version, "MODULE.bazel"), "rb") as f:
                module_file = f.read()
            source = source_entry(p["name"], version,
                                  _read_json(os.path.join(mdir, version, "source.json")), module_file)
        except (OSError, ValueError) as e:
            errors.append(str(e))
            continue
        entries.append({
            "name": p["name"],
            "version": version,
            "source": source,
            "targets": targets(p),
            "exclude": [{"pattern": x, "reason": r} for x, r in p["exclude"]],
            "flags": [{"flag": f, "reason": r} for f, r in p["flags"]],
            "bazel_version": p["bazel"][0] if p["bazel"] else None,
        })
    if errors:
        sys.exit("sync failed:\n  " + "\n  ".join(errors))

    write("projects.json", render_json(commit, entries))
    for p in projects:
        write(os.path.join(p["name"], "BUILD.bazel"), render_build(p))
    names = {p["name"] for p in projects}
    for d in sorted(os.listdir(ROOT)):
        build = os.path.join(ROOT, d, "BUILD.bazel")
        if d not in names and is_generated(build):
            os.remove(build)
            if not os.listdir(os.path.join(ROOT, d)):
                shutil.rmtree(os.path.join(ROOT, d))
    print("%d projects at BCR %s" % (len(entries), commit[:12]), file=sys.stderr)


if __name__ == "__main__":
    main()
