#!/usr/bin/env python3
"""Regenerates everything derived from MODULE.bazel and exclusions.txt.

For each project (each non-dev bazel_dep in MODULE.bazel) this:
  1. fetches the module's MODULE.bazel from the BCR and, if it has dev
     dependencies, writes patches/<module>.patch turning them into regular
     dependencies (dev deps of non-root modules are invisible, so most tests
     would not even analyze), plus a single_version_override applying it in
     overrides.MODULE.bazel;
  2. runs one `bb remote query` over every project's targets, minus
     exclusions.txt and everything depending on an excluded target;
  3. writes <module>/BUILD.bazel with an alias per non-test target and a
     `tests` test_suite listing every test;
  4. deletes generated files for projects no longer in MODULE.bazel;
  5. refreshes MODULE.bazel.lock through a remote run.

Run it as python3 tools/sync.py. It never builds locally.
"""

import difflib
import json
import os
import re
import shutil
import subprocess
import sys
import urllib.error
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BCR = "https://bcr.bazel.build"
GENERATED = "# Generated by tools/sync.py"
HEADER = GENERATED + " from @{repo}. Do not edit; see README.md.\n"
SUITE_NAME = "tests"
QUERY_FILE = ".sync-query.txt"

# ---------------------------------------------------------------------------
# Pure helpers (unit tested in tools/sync_test.py).


def blank_comments(text):
    """Replaces Starlark comments with spaces, keeping offsets and strings."""
    out, i, quote = list(text), 0, None
    while i < len(text):
        c = text[i]
        if quote:
            if c == "\\":
                i += 1
            elif c == quote:
                quote = None
        elif c in "\"'":
            quote = c
        elif c == "#":
            while i < len(text) and text[i] != "\n":
                out[i] = " "
                i += 1
            continue
        i += 1
    return "".join(out)


_CALL = re.compile(r"^(?:(\w+)\s*=\s*)?(\w+)\s*\(", re.M)


def calls(text):
    """Yields (start, end, func, var) for each top-level call statement.

    `text` must already have its comments blanked.
    """
    for m in _CALL.finditer(text):
        depth, i, quote = 0, m.end() - 1, None
        while i < len(text):
            c = text[i]
            if quote:
                if c == "\\":
                    i += 1
                elif c == quote:
                    quote = None
            elif c in "\"'":
                quote = c
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    yield m.start(), i + 1, m.group(2), m.group(1)
                    break
            i += 1


_STR = r"(?:\"([^\"]*)\"|'([^']*)')"


def kwarg(args, key):
    """Returns a string or bool keyword argument of a call, or None."""
    m = re.search(r"\b" + key + r"\s*=\s*(?:" + _STR + r"|(True|False))", args)
    if not m:
        return None
    if m.group(3):
        return m.group(3) == "True"
    return m.group(1) if m.group(1) is not None else m.group(2)


def parse_projects(module_text):
    """Returns [(module, version, repo)] for the non-dev bazel_deps."""
    text = blank_comments(module_text)
    out = []
    for start, end, func, _ in calls(text):
        args = text[start:end]
        if func != "bazel_dep" or kwarg(args, "dev_dependency"):
            continue
        name = kwarg(args, "name")
        out.append((name, kwarg(args, "version"), kwarg(args, "repo_name") or name))
    return out


_DEV_DEP = [
    re.compile(r",\s*dev_dependency\s*=\s*True\b"),  # not first
    re.compile(r"\bdev_dependency\s*=\s*True\s*,\s*"),  # first of several
    re.compile(r"\bdev_dependency\s*=\s*True\b"),  # only argument
]
_OVERRIDE = re.compile(
    r"\b(?:archive|git|local_path|single_version|multiple_version)_override\s*\("
    r"[^)]*?module_name\s*=\s*" + _STR,
    re.S,
)


def _dev_span(args):
    """(start, end) of the `dev_dependency = True` argument to cut from a call."""
    for pat in _DEV_DEP:
        m = pat.search(args)
        if m:
            return m.span()
    return None


def undev(module_text, available=lambda name, version: True):
    """Drops `dev_dependency = True` from a MODULE.bazel's calls.

    A dev bazel_dep stays dev-only when the module overrides it itself
    (non-root overrides are ignored, so it would not resolve) or when
    available(name, version) is false. So does any other dev call that
    mentions such a dep's repo, and the repos that a kept extension brings
    in through use_repo.
    """
    text = blank_comments(module_text)
    overridden = {a or b for a, b in _OVERRIDE.findall(text)}
    all_calls = list(calls(text))
    dev_calls = [c for c in all_calls if _DEV_DEP[2].search(text[c[0]:c[1]])]

    def mentions_kept(args):
        return any(re.search(r"@" + re.escape(r) + r"(?=//|[\"':])", args) for r in kept)

    kept, kept_vars, kept_calls = set(), set(), set()
    changed = True
    while changed:
        changed = False
        for start, end, func, var in dev_calls:
            args = text[start:end]
            if start in kept_calls:
                continue
            if func == "bazel_dep":
                name, version = kwarg(args, "name"), kwarg(args, "version")
                if name not in overridden and available(name, version):
                    continue
                kept.add(kwarg(args, "repo_name") or name)
            elif not mentions_kept(args):
                continue
            kept_calls.add(start)
            if var:
                kept_vars.add(var)
            changed = True
        for start, end, func, var in all_calls:
            args = text[start:end]
            m = re.match(r"use_repo\s*\(\s*(\w+)", args)
            if func == "use_repo" and m and m.group(1) in kept_vars:
                repos = {a or b for a, b in re.findall(_STR, args)}
                repos |= set(re.findall(r"(\w+)\s*=", args))
                if not repos <= kept:
                    kept |= repos
                    changed = True
    # Cut spans found in the comment-blanked text out of the original, which
    # has the same offsets, so comments survive.
    out, last = [], 0
    for start, end, _, _ in dev_calls:
        if start not in kept_calls:
            s, e = _dev_span(text[start:end])
            out.append(module_text[last:start + s])
            last = start + e
    out.append(module_text[last:])
    return "".join(out)


def make_patch(module_text, available=lambda name, version: True):
    """Returns a -p1 patch for MODULE.bazel that drops dev_dependency, or None."""
    new = undev(module_text, available)
    if new == module_text:
        return None
    return "".join(
        difflib.unified_diff(
            module_text.splitlines(True),
            new.splitlines(True),
            "a/MODULE.bazel",
            "b/MODULE.bazel",
        )
    )


def render_overrides(patched):
    """patched: [(module, version)] -> overrides.MODULE.bazel text."""
    out = [GENERATED + ". Do not edit; see README.md.\n"]
    for name, version in patched:
        out.append(
            "\nsingle_version_override(\n"
            '    module_name = "%s",\n'
            "    patch_strip = 1,\n"
            '    patches = ["//patches:%s.patch"],\n'
            '    version = "%s",\n'
            ")\n" % (name, name, version)
        )
    return "".join(out)


def parse_pattern(p):
    """Splits an exclusion into (repo, package, target).

    target is "..." for a subtree (@r//pkg/... or @r//...), else a target
    name. Returns None for anything else, e.g. @r//pkg, @r//pkg:all, @r//x*.
    """
    m = re.match(r"^@([\w.+-]+)//(?:\.\.\.|([^:\s*.][^:\s*]*)/\.\.\.|([^:\s*]*):([^:\s*]+))$", p)
    if not m or "..." in (m.group(3) or "") or m.group(4) in ("all", "all-targets", "..."):
        return None
    if m.group(4):
        return m.group(1), m.group(3), m.group(4)
    return m.group(1), m.group(2) or "", "..."


def parse_exclusions(text):
    """Returns [(pattern, reason)]; every pattern needs a reason."""
    out = []
    for n, line in enumerate(text.splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 1)
        if len(parts) < 2:
            raise ValueError("exclusions.txt:%d: %r has no reason" % (n, line))
        if not parse_pattern(parts[0]):
            raise ValueError("exclusions.txt:%d: %r is not @repo//pkg:target, "
                             "@repo//pkg/... or @repo//..." % (n, parts[0]))
        out.append((parts[0], parts[1]))
    return out


def query_expr(repos, patterns):
    """The one query: every non-manual rule, minus exclusions and their rdeps.

    rdeps(U, x) searches U's whole transitive closure, so a project target
    that reaches an excluded one through another repo is dropped too.
    """
    u = " + ".join("@%s//..." % r for r in repos)
    expr = "kind(rule, %s) except attr(tags, '[\\[ ]manual[,\\]]', %s)" % (u, u)
    if patterns:
        expr += " except rdeps(%s, %s)" % (u, " + ".join(patterns))
    return expr


_QUERY_LINE = re.compile(r"^(\S+) rule (@[^/\s]*//[^:\s]*:\S+)$")


def parse_query(output):
    """Returns {repo: [(kind, label)]} from --output=label_kind lines."""
    out = {}
    for line in output.splitlines():
        m = _QUERY_LINE.match(line.strip())
        if m:
            kind, label = m.groups()
            out.setdefault(label[1:label.index("//")], []).append((kind, label))
    return out


_ANSI = re.compile(r"\x1b\[[0-9;]*m")
_PATH = r"/external/([^/\s]+)/(?:(\S*?)/)?BUILD(?:\.bazel)?"
# An error located in some BUILD or .bzl file, or naming the target it's about.
_ATTRIBUTED = re.compile(r"^/\S*/external/[^/\s]+/\S*:\d+:\d+: | and referenced by '")
_BUILD_TRACE = re.compile(r"^\s*File \"[^\"]*" + _PATH + r"\"")
_SKIPPING = re.compile(r"^Skipping '(@[^']+)': (.*)")
_LOAD_ERROR = re.compile(r"error loading package '@@([^/']+)//([^']*)'")
_CONTAINS_ERRORS = re.compile(r"^package contains errors: ([^:\s]*)")
_NO_PACKAGE = re.compile(r"no such package '@@([^/']+)//([^']*)'")
_NO_TARGET = re.compile(r"no such target '@@([^/']+)//([^:']*):([^']+)'")
_NOISE = re.compile(r"^(Traceback \(most recent call last\):|Evaluation of query |"
                    r"An error occurred during the fetch of repository )")


def covered(repo, pkg, patterns):
    """Whether a subtree exclusion covers package @repo//pkg."""
    for p in patterns:
        r, prefix, target = parse_pattern(p)
        if r == repo and target == "..." and (
                not prefix or pkg == prefix or pkg.startswith(prefix + "/")):
            return True
    return False


def check_errors(output, canon, patterns):
    """Vets the errors of a failed query; returns problems, empty if all is well.

    canon maps the projects' canonical repo names (`zlib+`) to their apparent
    ones (`zlib`). This fails closed: every ERROR line must be one of
      - a package of a project that failed to load (its targets are missing
        from the output), which a subtree exclusion must cover;
      - an exclusion that matches nothing (stale), which is a problem;
      - an error about some target's dependencies, which leaves the target
        in the output for the build to deal with;
      - a known header or summary line.
    """
    lines = [_ANSI.sub("", l) for l in output.splitlines()]
    errors = [l[len("ERROR:"):].strip() for l in lines if l.startswith("ERROR:")]
    traced = set()
    for l in lines:
        m = _BUILD_TRACE.search(l)
        if m and m.group(1) in canon:
            traced.add((canon[m.group(1)], m.group(2) or ""))
    attributed = " ".join(e for e in errors if _ATTRIBUTED.search(e))

    def repeated(e):
        # Bazel repeats an attributed error without its location; compare
        # the part before the details, which can differ (temp paths).
        return e.split(": ", 1)[0] in attributed
    exact = {parse_pattern(p) for p in patterns if parse_pattern(p)[2] != "..."}
    failed, skipped, problems = set(traced), [], []
    for e in errors:
        m = _SKIPPING.match(e)
        if m:
            r, pkg, target = parse_pattern(m.group(1)) or (None, None, None)
            if m.group(1) in patterns:
                skipped.append((r, pkg))
            elif target == "..." and not pkg and r in canon.values():
                failed.add((r, ""))  # a whole project failed to load
            else:
                problems.append("unrecognised error: " + e)
            continue
        if _ATTRIBUTED.search(e) or _NOISE.match(e):
            continue
        m = _LOAD_ERROR.search(e)
        if m:
            if m.group(1) in canon:
                failed.add((canon[m.group(1)], m.group(2)))
            continue  # other repos: a dependency's package
        m = _CONTAINS_ERRORS.match(e)
        if m:
            if not any(p == m.group(1) for _, p in traced):
                problems.append("unrecognised error: " + e)
            continue
        m = _NO_TARGET.search(e) or _NO_PACKAGE.search(e)
        if m:
            r, pkg = canon.get(m.group(1)), m.group(2)
            target = m.group(3) if m.re is _NO_TARGET else None
            if any(x[:2] == (r, pkg) and (target is None or x[2] == target) for x in exact):
                problems.append("stale exclusion: " + e)
            elif not repeated(e):
                problems.append("unrecognised error: " + e)
            continue
        if not repeated(e):
            problems.append("unrecognised error: " + e)
    for r, pkg in skipped:  # A subtree whose packages all fail to load is fine.
        if not any(fr == r and (not pkg or fp == pkg or fp.startswith(pkg + "/"))
                   for fr, fp in failed):
            problems.append("stale exclusion: @%s//%s matches nothing" % (r, pkg + "/..." if pkg else "..."))
    for r, pkg in sorted(failed):
        if not covered(r, pkg, patterns):
            problems.append("package failed to load and isn't excluded: @%s//%s" % (r, pkg))
    if not errors:
        problems.append("query failed without ERROR lines")
    return problems


def alias_name(label):
    """@m//a/b:c -> a_b__c; @m//:c -> c."""
    pkg, name = label.split("//", 1)[1].split(":", 1)
    name = name.replace("/", "_")
    return name if not pkg else pkg.replace("/", "_") + "__" + name


def render_build(repo, targets):
    """targets: [(kind, label)] -> BUILD.bazel text for one project."""
    aliases, tests = {}, []
    for kind, label in sorted(set(targets), key=lambda t: t[1]):
        if kind == "test_suite":
            continue
        if kind.endswith("_test"):
            tests.append(label)
            continue
        name = base = alias_name(label)
        n = 2
        while name in aliases or name == SUITE_NAME:
            name = "%s_%d" % (base, n)
            n += 1
        aliases[name] = label
    out = [HEADER.format(repo=repo)]
    for name in sorted(aliases):
        out.append('\nalias(\n    name = "%s",\n    actual = "%s",\n)\n' % (name, aliases[name]))
    if tests:
        out.append('\ntest_suite(\n    name = "%s",\n    tests = [\n' % SUITE_NAME)
        out.extend('        "%s",\n' % t for t in tests)
        out.append("    ],\n)\n")
    return "".join(out)


def container_image(bazelrc):
    m = re.search(r"--remote_default_exec_properties=container-image=(\S+)", bazelrc)
    if not m:
        raise ValueError(".bazelrc sets no container-image exec property")
    return m.group(1)


# ---------------------------------------------------------------------------
# Side effects.


def read(path):
    with open(os.path.join(ROOT, path)) as f:
        return f.read()


def write(path, text):
    path = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)


def bb_remote(args=None, script=None):
    cmd = ["bb", "remote", "--container_image=" + container_image(read(".bazelrc"))]
    if script:
        cmd.append("--script=" + script)
    else:
        cmd += args + ["--config=remote-minimal"]
    print("+ " + " ".join(cmd), file=sys.stderr)
    p = subprocess.run(cmd, cwd=ROOT, stdout=subprocess.PIPE, text=True)
    for line in p.stdout.splitlines():
        if "invocation/" in line:
            print("  " + _ANSI.sub("", line).strip(), file=sys.stderr)
    return p.returncode, p.stdout


def fetch(url):
    with urllib.request.urlopen(url) as r:
        return r.read().decode()


_metadata = {}


def bcr_has(name, version):
    if name not in _metadata:
        try:
            _metadata[name] = json.loads(fetch("%s/modules/%s/metadata.json" % (BCR, name)))
        except urllib.error.HTTPError:
            _metadata[name] = {"versions": []}
    return version in _metadata[name]["versions"]


def is_generated(path, prefix=GENERATED):
    try:
        with open(path) as f:
            return f.readline().startswith(prefix)
    except OSError:
        return False


def sync_patches(projects):
    patched = []
    for name, version, _ in projects:
        url = "%s/modules/%s/%s/MODULE.bazel" % (BCR, name, version)
        text = make_patch(fetch(url), bcr_has)
        if text:
            write("patches/%s.patch" % name, GENERATED + ". Do not edit.\n" + text)
            patched.append((name, version))
    keep = {"%s.patch" % n for n, _ in patched} | {"BUILD.bazel"}
    for f in os.listdir(os.path.join(ROOT, "patches")):
        path = os.path.join(ROOT, "patches", f)
        if f not in keep and is_generated(path):
            os.remove(path)
    write("patches/BUILD.bazel", GENERATED + ": patches for overrides.MODULE.bazel.\n")
    write("overrides.MODULE.bazel", render_overrides(patched))


def sync_builds(projects, patterns):
    by_repo = {}
    if projects:
        repos = [repo for _, _, repo in projects]
        write(QUERY_FILE, query_expr(repos, patterns) + "\n")
        try:
            code, out = bb_remote(["query", "--query_file=" + QUERY_FILE, "--output=label_kind"])
        finally:
            os.remove(os.path.join(ROOT, QUERY_FILE))
        problems = []
        if code:
            problems = check_errors(out, {"%s+" % n: r for n, _, r in projects}, patterns)
        by_repo = parse_query(out)
        problems += ["@%s has no targets; exclude @%s//... if that's intended" % (r, r)
                     for _, _, r in projects
                     if not by_repo.get(r) and "@%s//..." % r not in patterns]
        if problems:
            sys.exit("query (exit %d) problems:\n  " % code + "\n  ".join(problems))
    for name, _, repo in projects:
        write(os.path.join(name, "BUILD.bazel"), render_build(repo, by_repo.get(repo, [])))
    names = {name for name, _, _ in projects}
    for d in os.listdir(ROOT):
        build = os.path.join(ROOT, d, "BUILD.bazel")
        if d not in names and is_generated(build, GENERATED + " from @"):
            os.remove(build)
            if not os.listdir(os.path.join(ROOT, d)):
                shutil.rmtree(os.path.join(ROOT, d))


def sync_lockfile():
    code, out = bb_remote(
        script="bazel mod deps --config=remote-minimal >&2 || exit 1; "
        "echo ===LOCK-BEGIN===; cat MODULE.bazel.lock; echo ===LOCK-END===",
    )
    m = re.search(r"===LOCK-BEGIN===\n(.*?\n)===LOCK-END===", out, re.S)
    if code or not m:
        sys.exit("could not refresh MODULE.bazel.lock (exit %d):\n%s" % (code, out[-3000:]))
    write("MODULE.bazel.lock", m.group(1))


def main():
    projects = parse_projects(read("MODULE.bazel"))
    patterns = [p for p, _ in parse_exclusions(read("exclusions.txt"))]
    sync_patches(projects)
    sync_builds(projects, patterns)
    sync_lockfile()


if __name__ == "__main__":
    main()
