ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BCR_GIT = "https://github.com/bazelbuild/bazel-central-registry"
BCR_URL = "https://bcr.bazel.build"
CACHE = os.path.join(os.path.expanduser("~"), ".cache", "bazel-matrix", "bcr")
GENERATED = "# Generated by tools/sync.py"
# The generated coverage report, relative to ROOT.
COVERAGE = "docs/coverage.md"
# `known-failing build`: the inner build fails, so both targets are manual;
# `known-failing test`: only the inner test fails, so only :test is.
KNOWN_FAILING = ("build", "test")

