#!/usr/bin/env python3
"""Regenerates everything derived from MODULE.bazel.

For each project (each non-dev bazel_dep in MODULE.bazel) this:
  1. fetches the module's MODULE.bazel from the BCR and, if it has dev
     dependencies, writes patches/<module>.patch turning them into regular
     dependencies (dev deps of non-root modules are invisible, so most tests
     would not even analyze), plus a single_version_override that applies it;
  2. runs one `bb remote query` over every project's targets;
  3. writes <module>/BUILD.bazel with an alias per non-test target and a
     `tests` test_suite listing every test, minus exclusions.txt;
  4. refreshes MODULE.bazel.lock through a remote run.

Run from anywhere: python3 tools/sync.py. It never builds locally.
"""

import argparse
import difflib
import os
import re
import subprocess
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BCR = "https://bcr.bazel.build"
CONTAINER_IMAGE = "docker://gcr.io/flame-public/rbe-ubuntu22-04:latest"
BEGIN = "# --- BEGIN GENERATED by tools/sync.py; do not edit ---"
END = "# --- END GENERATED ---"
HEADER = "# Generated by tools/sync.py from @{module}. Do not edit; see README.md.\n"
SUITE_NAME = "tests"

# ---------------------------------------------------------------------------
# Pure helpers (unit tested in tools/sync_test.py).


def strip_generated(module_text):
    """Returns MODULE.bazel text without the generated block."""
    start = module_text.find(BEGIN)
    if start < 0:
        return module_text
    end = module_text.find(END, start)
    if end < 0:
        raise ValueError("generated block in MODULE.bazel has no end marker")
    return module_text[:start] + module_text[end + len(END):].lstrip("\n")


def replace_generated(module_text, block):
    """Returns MODULE.bazel text with the generated block set to `block`."""
    base = strip_generated(module_text).rstrip("\n") + "\n"
    if not block:
        return base
    return base + "\n" + BEGIN + "\n" + block + END + "\n"


def _strip_comments(text):
    return "\n".join(line.split("#", 1)[0] for line in text.splitlines())


_BAZEL_DEP = re.compile(r"\bbazel_dep\s*\(([^)]*)\)", re.S)


def _kwarg(args, key):
    m = re.search(r"\b" + key + r"\s*=\s*(\"[^\"]*\"|True|False)", args)
    if not m:
        return None
    v = m.group(1)
    return v.strip('"') if v.startswith('"') else v == "True"


def parse_projects(module_text):
    """Returns [(name, version)] for the non-dev bazel_deps, in file order."""
    text = _strip_comments(strip_generated(module_text))
    out = []
    for m in _BAZEL_DEP.finditer(text):
        args = m.group(1)
        if _kwarg(args, "dev_dependency"):
            continue
        out.append((_kwarg(args, "name"), _kwarg(args, "version")))
    return out


_DEV_DEP = re.compile(r",(\s*)dev_dependency\s*=\s*True(\s*,)?")


def undev(module_text):
    """Drops every `dev_dependency = True` argument from a MODULE.bazel."""

    def repl(m):
        # Keep a trailing comma only if one preceded and followed the kwarg on
        # separate lines (multi-line call); otherwise just remove the kwarg.
        return "," if m.group(2) and "\n" in m.group(1) else ""

    return _DEV_DEP.sub(repl, module_text)


def make_patch(module_text):
    """Returns a -p1 patch for MODULE.bazel that drops dev_dependency, or None."""
    new = undev(module_text)
    if new == module_text:
        return None
    return "".join(
        difflib.unified_diff(
            module_text.splitlines(True),
            new.splitlines(True),
            "a/MODULE.bazel",
            "b/MODULE.bazel",
        )
    )


def render_overrides(patched):
    """patched: [(name, version)] -> single_version_override block text."""
    out = []
    for name, version in patched:
        out.append(
            "single_version_override(\n"
            '    module_name = "%s",\n'
            '    patch_strip = 1,\n'
            '    patches = ["//patches:%s.patch"],\n'
            '    version = "%s",\n'
            ")\n" % (name, name, version)
        )
    return "\n".join(out)


_QUERY_LINE = re.compile(r"^(\S+) rule (@[^/\s]*//[^:\s]*:\S+)$")


def parse_query(output):
    """Returns {repo: [(kind, label)]} from --output=label_kind lines."""
    out = {}
    for line in output.splitlines():
        m = _QUERY_LINE.match(line.strip())
        if not m:
            continue
        kind, label = m.groups()
        repo = label[1:label.index("//")]
        out.setdefault(repo, []).append((kind, label))
    return out


def parse_exclusions(text):
    """Returns [(pattern, reason)]; every pattern needs a reason."""
    out = []
    for n, line in enumerate(text.splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 1)
        if len(parts) < 2:
            raise ValueError("exclusions.txt:%d: %r has no reason" % (n, line))
        out.append((parts[0], parts[1]))
    return out


def is_excluded(label, patterns):
    for p in patterns:
        if p.endswith("//..."):
            if label.startswith(p[:-3]):
                return True
        elif p.endswith("/..."):
            prefix = p[:-4]
            pkg = label.split(":", 1)[0]
            if pkg == prefix or pkg.startswith(prefix + "/"):
                return True
        elif label == p:
            return True
    return False


def alias_name(label):
    """@m//a/b:c -> a_b__c; @m//:c -> c."""
    pkg, name = label.split("//", 1)[1].split(":", 1)
    name = name.replace("/", "_")
    return name if not pkg else pkg.replace("/", "_") + "__" + name


def is_test(kind):
    return kind.endswith("_test")


def render_build(module, targets, patterns):
    """targets: [(kind, label)] -> BUILD.bazel text for //<module>."""
    aliases, tests = {}, []
    for kind, label in sorted(set(targets), key=lambda t: t[1]):
        if kind == "test_suite" or is_excluded(label, patterns):
            continue
        if is_test(kind):
            tests.append(label)
            continue
        name = alias_name(label)
        base, n = name, 2
        while name in aliases or name == SUITE_NAME:
            name = "%s_%d" % (base, n)
            n += 1
        aliases[name] = label
    out = [HEADER.format(module=module)]
    for name in sorted(aliases):
        out.append(
            '\nalias(\n    name = "%s",\n    actual = "%s",\n)\n' % (name, aliases[name])
        )
    out.append('\ntest_suite(\n    name = "%s",\n    tests = [\n' % SUITE_NAME)
    out.extend('        "%s",\n' % t for t in tests)
    out.append("    ],\n)\n")
    return "".join(out)


# ---------------------------------------------------------------------------
# Side effects.


def bb_remote(args, script=None):
    cmd = ["bb", "remote", "--container_image=" + CONTAINER_IMAGE]
    if script:
        cmd.append("--script=" + script)
    else:
        cmd += args + ["--config=remote-minimal"]
    print("+ " + " ".join(cmd), file=sys.stderr)
    p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    out = p.stdout + p.stderr
    for line in out.splitlines():
        if "invocation/" in line:
            print("  " + line.strip(), file=sys.stderr)
    return p.returncode, out


def fetch(url):
    with urllib.request.urlopen(url) as r:
        return r.read().decode()


def write(path, text):
    path = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)


def sync_patches(projects, nopatch):
    patched = []
    for name, version in projects:
        path = os.path.join("patches", name + ".patch")
        text = None
        if name not in nopatch:
            text = make_patch(fetch("%s/modules/%s/%s/MODULE.bazel" % (BCR, name, version)))
        if text:
            write(path, text)
            patched.append((name, version))
        elif os.path.exists(os.path.join(ROOT, path)):
            os.remove(os.path.join(ROOT, path))
    write("patches/BUILD.bazel", "# Patches generated by tools/sync.py.\n")
    module_path = os.path.join(ROOT, "MODULE.bazel")
    write("MODULE.bazel", replace_generated(open(module_path).read(), render_overrides(patched)))


def sync_builds(projects, patterns):
    universe = " + ".join("@%s//..." % name for name, _ in projects)
    expr = "kind(rule, %s) except attr(tags, '\\bmanual\\b', %s)" % (universe, universe)
    code, out = bb_remote(["query", expr, "--output=label_kind"])
    by_repo = parse_query(out)
    if not by_repo:
        sys.exit("query returned no targets (exit %d):\n%s" % (code, out[-3000:]))
    for name, _ in projects:
        targets = by_repo.get(name, [])
        if not targets:
            print("warning: no targets found for @%s" % name, file=sys.stderr)
        write(os.path.join(name, "BUILD.bazel"), render_build(name, targets, patterns))


def sync_lockfile():
    code, out = bb_remote(
        None,
        script="bazel mod deps --config=remote-minimal >/dev/null 2>&1 || exit 1; "
        "echo ===LOCK-BEGIN===; cat MODULE.bazel.lock; echo ===LOCK-END===",
    )
    m = re.search(r"===LOCK-BEGIN===\n(.*?\n)===LOCK-END===", out, re.S)
    if code or not m:
        sys.exit("could not refresh MODULE.bazel.lock (exit %d):\n%s" % (code, out[-3000:]))
    write("MODULE.bazel.lock", m.group(1))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.parse_args()
    projects = parse_projects(open(os.path.join(ROOT, "MODULE.bazel")).read())
    entries = parse_exclusions(open(os.path.join(ROOT, "exclusions.txt")).read())
    nopatch = {p[len("nopatch:"):] for p, _ in entries if p.startswith("nopatch:")}
    patterns = [p for p, _ in entries if not p.startswith("nopatch:")]
    sync_patches(projects, nopatch)
    sync_builds(projects, patterns)
    sync_lockfile()


if __name__ == "__main__":
    main()
