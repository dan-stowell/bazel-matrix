#!/usr/bin/env python3
"""Regenerates projects.json and //<module>:BUILD.bazel from projects.txt.

    python3 tools/sync.py           # at the BCR commit projects.json records
    python3 tools/sync.py --update  # at the BCR's current HEAD

It keeps a sparse, shallow clone of the Bazel Central Registry
(metadata.json, source.json and MODULE.bazel files only) in
~/.cache/bazel-matrix/bcr, checked out at the recorded commit, so re-running
it changes nothing. For each project in projects.txt it picks the pinned
version, or else the newest stable, non-yanked version whose
bazel_compatibility admits its inner Bazel (DEFAULT_INNER_BAZEL in
tools/versions.bzl unless pinned); records its source (archive, integrity,
strip_prefix, patches, overlay and MODULE.bazel, as bcr.bazel.build URLs with
their integrity) in projects.json; and writes //<module>:BUILD.bazel.
Projects that can't be used (deprecated, no compatible version, an
unsupported source type) are skipped with the reason, recorded in
projects.json. Generated packages of projects not written are deleted.
"""

import argparse
import base64
import collections
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BCR_GIT = "https://github.com/bazelbuild/bazel-central-registry"
BCR_URL = "https://bcr.bazel.build"
CACHE = os.path.join(os.path.expanduser("~"), ".cache", "bazel-matrix", "bcr")
GENERATED = "# Generated by tools/sync.py"
# `known-failing build`: the inner build fails, so both targets are manual;
# `known-failing test`: only the inner test fails, so only :test is.
KNOWN_FAILING = ("build", "test")

# ---------------------------------------------------------------------------
# projects.txt

# `rc-drop <file> `<exact line>` reason`: <file> relative to the source root.
_RC_DROP = re.compile(r"rc-drop\s+(\S+)\s+`([^`]+)`\s+(\S.*)")


def parse_projects_txt(text):
    """[{name, version, exclude: [(pattern, reason)], flags: [(flag, reason)],
    bazel: (version, reason) or None, known_failing: (build|test, reason) or
    None, overrides: [(module, version, reason)], rc_drop: [(file, line,
    reason)]}] from projects.txt.

    A project line is `module` or `module@version`. Indented lines below it
    are `-//pattern reason`, `--flag reason`, `bazel <version> reason`,
    `known-failing build|test reason`, `override <module> <version>
    reason` or ``rc-drop <file> `<exact line>` reason``; every one needs a
    reason. A blank line ends a project: an
    indented line after one is an error, not part of the project above.
    """
    projects, errors = [], []
    blank = False
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line:
            blank = True
        if not line or line.startswith("#"):
            continue
        after_blank, blank = blank, False
        if not raw[0].isspace():
            name, _, version = line.partition("@")
            if not re.fullmatch(r"[a-z][a-z0-9._-]*", name) or " " in line:
                errors.append("line %d: bad project %r" % (n, line))
                continue
            if any(p["name"] == name for p in projects):
                errors.append("line %d: %s listed twice" % (n, name))
            projects.append({"name": name, "version": version or None,
                             "exclude": [], "flags": [], "bazel": None,
                             "known_failing": None, "overrides": [], "rc_drop": []})
            continue
        if not projects:
            errors.append("line %d: indented line before any project" % n)
            continue
        if after_blank:
            errors.append("line %d: indented line after a blank line; remove the blank line "
                          "if it belongs to %s" % (n, projects[-1]["name"]))
            continue
        words = {"bazel": 2, "known-failing": 2, "override": 3, "rc-drop": 2}.get(line.split()[0], 1)
        parts = line.split(None, words)
        p = projects[-1]
        if parts[0] == "override" and len(parts) == 4 and re.fullmatch(r"[a-z][a-z0-9._-]*", parts[1]):
            p["overrides"].append((parts[1], parts[2], parts[3]))
        elif parts[0] == "rc-drop":
            m = _RC_DROP.fullmatch(line)
            path = m and m.group(1)
            if not m or path.startswith("/") or ".." in path.split("/") or path == "MODULE.bazel":
                errors.append("line %d: expected rc-drop <file in the source tree, not MODULE.bazel> "
                              "`<exact line>` reason: %r" % (n, line))
            elif (path, m.group(2).strip()) in [(f, l) for f, l, _ in p["rc_drop"]]:
                errors.append("line %d: %s: the same rc-drop twice" % (n, p["name"]))
            else:
                p["rc_drop"].append((path, m.group(2).strip(), m.group(3)))
        elif parts[0] == "bazel" and len(parts) == 3:
            p["bazel"] = (parts[1], parts[2])
        elif parts[0] == "known-failing" and len(parts) == 3 and parts[1] in KNOWN_FAILING:
            if p["known_failing"]:
                errors.append("line %d: %s is known-failing twice" % (n, p["name"]))
            p["known_failing"] = (parts[1], parts[2])
        elif len(parts) < 2:
            errors.append("line %d: %r needs a reason" % (n, line))
        elif re.fullmatch(r"-(//|@)\S*", parts[0]) and "*" not in parts[0]:
            p["exclude"].append((parts[0][1:], parts[1]))
        elif parts[0].startswith("--"):
            p["flags"].append((parts[0], parts[1]))
        else:
            errors.append("line %d: expected -//pattern, --flag, bazel <version>, "
                          "known-failing build|test, override <module> <version> or "
                          "rc-drop <file> `<line>`, each with a reason: %r" % (n, line))
    if errors:
        raise ValueError("projects.txt:\n  " + "\n  ".join(errors))
    return projects


# ---------------------------------------------------------------------------
# Version selection.


def _ident(s):
    return (0, int(s), "") if s.isdigit() else (1, 0, s)


def version_key(v):
    """Sort key following Bazel's module version ordering."""
    v = v.split("+", 1)[0]
    rel, _, pre = v.partition("-")
    relk = tuple(_ident(x) for x in rel.split(".")) if rel else ()
    prek = (1,) if not pre else (0, tuple(_ident(x) for x in pre.split(".")))
    return ((1,) if not rel else (0,), relk, prek)


def is_stable(v):
    return "-" not in v.split("+", 1)[0]


def _num(v):
    return tuple(int(x) for x in re.findall(r"\d+", v)[:3])


def bazel_compatible(constraints, bazel):
    """Whether bazel_compatibility constraints (">=7.2.1", "-9.0.0") admit bazel."""
    b = _num(bazel)
    for c in constraints:
        m = re.match(r"^(>=|<=|>|<|-)\s*(\S+)$", c.strip())
        if not m:
            continue
        op, v = m.group(1), _num(m.group(2))
        if not {">=": b >= v, "<=": b <= v, ">": b > v, "<": b < v, "-": b != v}[op]:
            return False
    return True


def bazel_compatibility(module_text):
    """The bazel_compatibility list of a MODULE.bazel's module() call."""
    text = re.sub(r"#[^\n]*", "", module_text)
    m = re.search(r"\bmodule\s*\((.*?)\)", text, re.S)
    if not m:
        return []
    c = re.search(r"bazel_compatibility\s*=\s*\[([^\]]*)\]", m.group(1))
    return re.findall(r"[\"']([^\"']*)[\"']", c.group(1)) if c else []


def pick(metadata, module_text_for, bazel):
    """(version, None) for a module's newest usable version, or (None, why)."""
    if metadata.get("deprecated"):
        return None, "deprecated"
    yanked = metadata.get("yanked_versions") or {}
    versions = sorted((v for v in metadata.get("versions", []) if v not in yanked), key=version_key)
    if not versions:
        return None, "all versions yanked"
    # Date versions like re2's 2025-11-05 parse as prereleases; a module
    # with nothing else uses its latest.
    stable = [v for v in versions if is_stable(v)] or versions
    for v in reversed(stable):
        text = module_text_for(v)
        if text is not None and bazel_compatible(bazel_compatibility(text), bazel):
            return v, None
    latest = module_text_for(stable[-1]) or ""
    return None, "no version admits Bazel %s (latest %s: bazel_compatibility %s)" % (
        bazel, stable[-1], bazel_compatibility(latest))


# ---------------------------------------------------------------------------
# projects.json and BUILD files.


def integrity(data):
    return "sha256-" + base64.b64encode(hashlib.sha256(data).digest()).decode()


_OVERRIDE_CALL = re.compile(
    r"\b(single_version|multiple_version|archive|git|local_path)_override\s*\(([^)]*)\)", re.S)


def module_append(overrides, module_text, has_version=None):
    """(module_remove, module_append) for a project's `override` lines: the
    exact local_path_override(...) texts that tools/sources.bzl removes from
    its MODULE.bazel, and the lines it then appends.

    An override of a module the registry's MODULE.bazel local_path_override()s
    replaces that override; sync records its text, which must be whole lines
    found once (as tools/sources.bzl removes it; see remove_lines), with a
    literal module_name and no nested parentheses. has_version(module, version), if given, says whether
    the BCR has that version.

    Raises ValueError when projects.txt overrides a module twice, when the
    registry's MODULE.bazel already overrides it some other way (a second
    override is an error in Bazel), when its local_path_override can't be
    removed literally, or when the MODULE.bazel include()s files sync can't
    see.
    """
    modules = [m for m, _, _ in overrides]
    twice = sorted({m for m in modules if modules.count(m) > 1})
    if twice:
        raise ValueError("override listed twice for " + ", ".join(twice))
    for m, v, _ in overrides:
        if has_version and not has_version(m, v):
            raise ValueError("%s@%s isn't in the BCR" % (m, v))
    # Comments blanked out, keeping every offset.
    text = re.sub(r"#[^\n]*", lambda c: " " * len(c.group()), module_text)
    if re.search(r"\binclude\s*\(", text):
        raise ValueError("its MODULE.bazel include()s other files, which may already "
                         "override; sync can't check them")
    remove = []
    for call in _OVERRIDE_CALL.finditer(text):
        kind, args = call.group(1), call.group(2)
        name = re.search(r"module_name\s*=\s*([\"'])([^\"']+)\1\s*(,|$)", args)
        if not name:
            raise ValueError("its MODULE.bazel has a %s_override whose module_name isn't a "
                             "string literal; sync can't check it" % kind)
        name = name.group(2)
        if name not in modules:
            continue
        if kind != "local_path":
            raise ValueError("its MODULE.bazel already has %s_override for %s" % (kind, name))
        literal = module_text[call.start():call.end()]
        if "(" in args or remove_lines(module_text, literal) is None:
            raise ValueError("its MODULE.bazel's local_path_override for %s isn't whole lines "
                             "found once; sync can't remove it" % name)
        remove.append(literal)
    return remove, render_append(overrides)


def remove_lines(text, lines):
    """text without the whole lines `lines`, compared with surrounding
    whitespace stripped, or None unless they occur exactly once. The same as
    tools/sources.bzl's _remove_lines."""
    have = text.split("\n")
    want = [w.strip() for w in lines.split("\n")]
    hits = [i for i in range(len(have) - len(want) + 1)
            if [h.strip() for h in have[i:i + len(want)]] == want]
    if len(hits) != 1 or not lines.strip():
        return None
    return "\n".join(have[:hits[0]] + have[hits[0] + len(want):])


def rc_remove(rc_drop):
    """projects.json's `remove` entries for a project's rc-drop lines."""
    out = {}
    for path, line, _ in rc_drop:
        out.setdefault(path, []).append(line)
    return out


def render_append(overrides):
    """module_append's text, without its checks of the registry's MODULE.bazel."""
    return "".join("\n# bazel-matrix: %s\nsingle_version_override(module_name = %s, version = %s)\n"
                   % (reason, _q(m), _q(v)) for m, v, reason in overrides)


def source_entry(name, version, source, module_file):
    """projects.json's `source` for a BCR source.json and MODULE.bazel (bytes).

    Like Bazel fetching from a registry, the registry's MODULE.bazel replaces
    the source's: a .bcr.N version may change only that file.
    """
    kind = source.get("type", "archive")
    if kind != "archive":
        raise ValueError("%s@%s: %s sources aren't supported yet" % (name, version, kind))
    base = "%s/modules/%s/%s" % (BCR_URL, name, version)
    entry = {
        "urls": [source["url"]] + list(source.get("mirror_urls", [])),
        "integrity": source["integrity"],
    }
    for key in ("strip_prefix", "archive_type"):
        if source.get(key):
            entry[key] = source[key]
    if source.get("patches"):
        entry["patches"] = [{"url": "%s/patches/%s" % (base, p), "integrity": i}
                            for p, i in source["patches"].items()]
        entry["patch_strip"] = int(source.get("patch_strip", 0))
    if source.get("overlay"):
        entry["overlay"] = [{"path": p, "url": "%s/overlay/%s" % (base, p), "integrity": i}
                            for p, i in sorted(source["overlay"].items())]
    entry["module_file"] = {"url": base + "/MODULE.bazel", "integrity": integrity(module_file)}
    return entry


def _q(s):
    return json.dumps(s)


def render_build(project):
    out = [GENERATED + " from projects.txt. Do not edit; see README.md.\n\n",
           'load("//tools:project.bzl", "project")\n\n',
           "project(\n",
           "    name = %s,\n" % _q(project["name"]),
           "    targets = [\n",
           '        "//...",\n']
    for pattern, reason in project["exclude"]:
        out.append("        # %s\n        %s,\n" % (reason, _q("-" + pattern)))
    out.append("    ],\n")
    if project["flags"]:
        out.append("    flags = [\n")
        for flag, reason in project["flags"]:
            out.append("        # %s\n        %s,\n" % (reason, _q(flag)))
        out.append("    ],\n")
    if project["bazel"]:
        out.append("    # %s\n    bazel_version = %s,\n" % (project["bazel"][1], _q(project["bazel"][0])))
    if project.get("known_failing"):
        what, reason = project["known_failing"]
        out.append("    # %s\n    known_failing = %s,\n" % (reason, _q(what)))
    out.append(")\n")
    return "".join(out)


def build_files(projects, names):
    """{<module>/BUILD.bazel: its text} for the projects named (those
    projects.json fetches).

    Depends only on projects.txt (parsed) and projects.json, so
    tools/generated_test.py can check the committed files without the BCR.
    """
    return {p["name"] + "/BUILD.bazel": render_build(p) for p in projects if p["name"] in names}


def module_mismatch(projects, data):
    """Problems with projects.json against projects.txt: its modules, their
    order, pinned versions and override lines. (What sync gets from the BCR,
    like unpinned versions, isn't checked.)"""
    listed = [p["name"] for p in projects]
    fetched = [e["name"] for e in data["projects"]]
    errors = []
    a = collections.Counter(listed)
    b = collections.Counter(fetched + [s["name"] for s in data["skipped"]])
    if a != b:
        errors.append("projects.json and projects.txt differ on: " + ", ".join(sorted((a - b) + (b - a))))
    if [m for m in fetched if m in a] != [m for m in listed if m in fetched]:
        errors.append("projects.json's projects are not in projects.txt's order")
    by_name = {p["name"]: p for p in projects}
    for e in data["projects"]:
        p = by_name.get(e["name"])
        if not p:
            continue
        if p["version"] and p["version"] != e["version"]:
            errors.append("%s: pinned %s, projects.json has %s" % (p["name"], p["version"], e["version"]))
        if render_append(p["overrides"]) != e["source"].get("module_append", ""):
            errors.append("%s: projects.json's module_append doesn't match its override lines" % p["name"])
        remove = dict(e["source"].get("remove", {}))
        for text in remove.pop("MODULE.bazel", []):
            name = re.search(r"module_name\s*=\s*[\"']([^\"']+)", text)
            if not text.startswith("local_path_override") or not name or name.group(1) not in [
                    m for m, _, _ in p["overrides"]]:
                errors.append("%s: projects.json's MODULE.bazel removals don't match its override lines" % p["name"])
        if rc_remove(p["rc_drop"]) != remove:
            errors.append("%s: projects.json's rc file removals don't match its rc-drop lines" % p["name"])
    for s in data["skipped"]:
        p = by_name.get(s["name"])
        # sync skips a pinned project only for its source type, with a
        # reason naming that version (see source_entry).
        if p and p["version"] and not s["reason"].startswith("%s@%s:" % (p["name"], p["version"])):
            errors.append("%s: pinned %s, but projects.json skips it: %s" % (p["name"], p["version"], s["reason"]))
    return errors


def render_json(commit, entries, skipped):
    """projects.json: what tools/sources.bzl fetches, plus the skipped projects."""
    return json.dumps({"bcr_commit": commit, "projects": entries, "skipped": skipped},
                      indent=2) + "\n"


def counts(projects, skipped):
    """The numbers sync prints."""
    kf = [p["known_failing"][0] for p in projects if p.get("known_failing")]
    return {
        "projects": len(projects),
        "known_failing_build": kf.count("build"),
        "known_failing_test": kf.count("test"),
        "exclusions": sum(len(p["exclude"]) for p in projects),
        "flags": sum(len(p["flags"]) for p in projects),
        "overrides": sum(len(p.get("overrides", [])) for p in projects),
        "rc_drops": sum(len(p.get("rc_drop", [])) for p in projects),
        "skipped": len(skipped),
    }


def status_line(c):
    return ("%(projects)d projects: %(known_failing_build)d known-failing build, "
            "%(known_failing_test)d known-failing test, %(exclusions)d target exclusions, "
            "%(flags)d extra flags, %(overrides)d module overrides, %(rc_drops)d rc drops, "
            "%(skipped)d skipped by sync" % c)


def default_inner_bazel(versions_bzl):
    m = re.search(r'^DEFAULT_INNER_BAZEL = "([^"]+)"', versions_bzl, re.M)
    if not m:
        raise ValueError("tools/versions.bzl sets no DEFAULT_INNER_BAZEL")
    return m.group(1)


# ---------------------------------------------------------------------------
# Side effects.


def read(path):
    with open(os.path.join(ROOT, path)) as f:
        return f.read()


def write(path, text):
    path = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)


def is_generated(path):
    try:
        with open(path) as f:
            return f.readline().startswith(GENERATED)
    except OSError:
        return False


def checkout_bcr(commit, path=CACHE):
    """Checks out the sparse BCR clone at commit (or HEAD if None); returns the commit."""
    git = ["git", "-C", path]
    if not os.path.isdir(os.path.join(path, ".git")):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        subprocess.run(["git", "clone", "-q", "--depth=1", "--filter=blob:none",
                        "--no-checkout", BCR_GIT, path], check=True)
    subprocess.run(git + ["sparse-checkout", "set", "--no-cone", "/modules/*/metadata.json",
                          "/modules/*/*/source.json", "/modules/*/*/MODULE.bazel"], check=True)
    have = subprocess.run(git + ["rev-parse", "-q", "--verify", "HEAD"],
                          stdout=subprocess.PIPE, text=True).stdout.strip()
    if not commit or have != commit:
        subprocess.run(git + ["fetch", "-q", "--depth=1", "origin", commit or "HEAD"], check=True)
        subprocess.run(git + ["checkout", "-q", "--force", "FETCH_HEAD"], check=True)
    return subprocess.run(git + ["rev-parse", "HEAD"], stdout=subprocess.PIPE, text=True,
                          check=True).stdout.strip()


def _read_json(path):
    with open(path) as f:
        return json.load(f)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--update", action="store_true", help="move to the BCR's current HEAD")
    args = ap.parse_args()

    projects = parse_projects_txt(read("projects.txt"))
    old = {}
    if os.path.exists(os.path.join(ROOT, "projects.json")):
        old = json.loads(read("projects.json"))
    commit = checkout_bcr(None if args.update else old.get("bcr_commit"))
    modules = os.path.join(CACHE, "modules")
    bazel = default_inner_bazel(read("tools/versions.bzl"))

    entries, skipped, errors = [], [], []
    for p in projects:
        mdir = os.path.join(modules, p["name"])
        if not os.path.isfile(os.path.join(mdir, "metadata.json")):
            errors.append("%s: not in the BCR" % p["name"])
            continue
        version = p["version"]
        if not version:
            def text_for(v, mdir=mdir):
                path = os.path.join(mdir, v, "MODULE.bazel")
                return open(path, encoding="utf-8", errors="replace").read() if os.path.isfile(path) else None
            version, why = pick(_read_json(os.path.join(mdir, "metadata.json")), text_for,
                                p["bazel"][0] if p["bazel"] else bazel)
            if why:
                skipped.append({"name": p["name"], "reason": why})
                continue
        try:
            with open(os.path.join(mdir, version, "MODULE.bazel"), "rb") as f:
                module_file = f.read()
            source = _read_json(os.path.join(mdir, version, "source.json"))
        except OSError as e:
            errors.append("%s@%s: %s" % (p["name"], version, e))
            continue
        try:
            entry = source_entry(p["name"], version, source, module_file)
        except ValueError as e:
            skipped.append({"name": p["name"], "reason": str(e)})
            continue
        if p["overrides"]:
            try:
                remove, entry["module_append"] = module_append(
                    p["overrides"], module_file.decode("utf-8", "replace"),
                    lambda m, v: os.path.isfile(os.path.join(modules, m, v, "MODULE.bazel")))
            except ValueError as e:
                errors.append("%s: override: %s" % (p["name"], e))
                continue
            if remove:
                entry["remove"] = {"MODULE.bazel": remove}
        if p["rc_drop"]:
            entry.setdefault("remove", {}).update(rc_remove(p["rc_drop"]))
        entries.append({"name": p["name"], "version": version, "source": entry})
    if errors:
        sys.exit("sync failed:\n  " + "\n  ".join(errors))
    for s in skipped:
        print("skip %s: %s" % (s["name"], s["reason"]), file=sys.stderr)

    write("projects.json", render_json(commit, entries, skipped))
    names = {e["name"] for e in entries}
    for path, text in build_files(projects, names).items():
        write(path, text)
    for d in sorted(os.listdir(ROOT)):
        build = os.path.join(ROOT, d, "BUILD.bazel")
        if d not in names and is_generated(build):
            os.remove(build)
            if not os.listdir(os.path.join(ROOT, d)):
                shutil.rmtree(os.path.join(ROOT, d))
    used = [p for p in projects if p["name"] in names]
    print("%s; BCR %s" % (status_line(counts(used, skipped)), commit[:12]), file=sys.stderr)


if __name__ == "__main__":
    main()
