# projects.json and BUILD files.


def integrity(data):
    return "sha256-" + base64.b64encode(hashlib.sha256(data).digest()).decode()


_OVERRIDE_CALL = re.compile(
    r"\b(single_version|multiple_version|archive|git|local_path)_override\s*\(([^)]*)\)", re.S)


def module_append(overrides, module_text, has_version=None):
    """(module_remove, module_append) for a project's `override` lines: the
    exact local_path_override(...) texts that tools/sources.bzl removes from
    its MODULE.bazel, and the lines it then appends.

    An override of a module the registry's MODULE.bazel local_path_override()s
    replaces that override; sync records its text, which must be whole lines
    found once (as tools/sources.bzl removes it; see remove_lines), with a
    literal module_name and no nested parentheses. has_version(module, version), if given, says whether
    the BCR has that version.

    Raises ValueError when projects.txt overrides a module twice, when the
    registry's MODULE.bazel already overrides it some other way (a second
    override is an error in Bazel), when its local_path_override can't be
    removed literally, or when the MODULE.bazel include()s files sync can't
    see.
    """
    modules = [m for m, _, _ in overrides]
    twice = sorted({m for m in modules if modules.count(m) > 1})
    if twice:
        raise ValueError("override listed twice for " + ", ".join(twice))
    for m, v, _ in overrides:
        if has_version and not has_version(m, v):
            raise ValueError("%s@%s isn't in the BCR" % (m, v))
    # Comments blanked out, keeping every offset.
    text = re.sub(r"#[^\n]*", lambda c: " " * len(c.group()), module_text)
    if re.search(r"\binclude\s*\(", text):
        raise ValueError("its MODULE.bazel include()s other files, which may already "
                         "override; sync can't check them")
    remove = []
    for call in _OVERRIDE_CALL.finditer(text):
        kind, args = call.group(1), call.group(2)
        name = re.search(r"module_name\s*=\s*([\"'])([^\"']+)\1\s*(,|$)", args)
        if not name:
            raise ValueError("its MODULE.bazel has a %s_override whose module_name isn't a "
                             "string literal; sync can't check it" % kind)
        name = name.group(2)
        if name not in modules:
            continue
        if kind != "local_path":
            raise ValueError("its MODULE.bazel already has %s_override for %s" % (kind, name))
        literal = module_text[call.start():call.end()]
        if "(" in args or remove_lines(module_text, literal) is None:
            raise ValueError("its MODULE.bazel's local_path_override for %s isn't whole lines "
                             "found once; sync can't remove it" % name)
        remove.append(literal)
    return remove, render_append(overrides)


def remove_lines(text, lines):
    """text without the whole lines `lines`, compared with surrounding
    whitespace stripped, or None unless they occur exactly once. The same as
    tools/sources.bzl's _remove_lines."""
    have = text.split("\n")
    want = [w.strip() for w in lines.split("\n")]
    hits = [i for i in range(len(have) - len(want) + 1)
            if [h.strip() for h in have[i:i + len(want)]] == want]
    if len(hits) != 1 or not lines.strip():
        return None
    return "\n".join(have[:hits[0]] + have[hits[0] + len(want):])


def rc_remove(rc_drop):
    """projects.json's `remove` entries for a project's rc-drop lines."""
    out = {}
    for path, line, _ in rc_drop:
        out.setdefault(path, []).append(line)
    return out


def render_append(overrides):
    """module_append's text, without its checks of the registry's MODULE.bazel."""
    return "".join("\n# bazel-matrix: %s\nsingle_version_override(module_name = %s, version = %s)\n"
                   % (reason, _q(m), _q(v)) for m, v, reason in overrides)


def source_entry(name, version, source, module_file):
    """projects.json's `source` for a BCR source.json and MODULE.bazel (bytes).

    Like Bazel fetching from a registry, the registry's MODULE.bazel replaces
    the source's: a .bcr.N version may change only that file.
    """
    kind = source.get("type", "archive")
    if kind != "archive":
        raise ValueError("%s@%s: %s sources aren't supported yet" % (name, version, kind))
    base = "%s/modules/%s/%s" % (BCR_URL, name, version)
    entry = {
        "urls": [source["url"]] + list(source.get("mirror_urls", [])),
        "integrity": source["integrity"],
    }
    for key in ("strip_prefix", "archive_type"):
        if source.get(key):
            entry[key] = source[key]
    if source.get("patches"):
        entry["patches"] = [{"url": "%s/patches/%s" % (base, p), "integrity": i}
                            for p, i in source["patches"].items()]
        entry["patch_strip"] = int(source.get("patch_strip", 0))
    if source.get("overlay"):
        entry["overlay"] = [{"path": p, "url": "%s/overlay/%s" % (base, p), "integrity": i}
                            for p, i in sorted(source["overlay"].items())]
    entry["module_file"] = {"url": base + "/MODULE.bazel", "integrity": integrity(module_file)}
    return entry


def _q(s):
    return json.dumps(s)


def render_build(project, deps=()):
    out = [GENERATED + " from projects.txt. Do not edit; see README.md.\n\n",
           'load("//tools:project.bzl", "project")\n\n',
           "project(\n",
           "    name = %s,\n" % _q(project["name"]),
           "    targets = [\n",
           '        "//...",\n']
    for pattern, reason in project["exclude"]:
        out.append("        # %s\n        %s,\n" % (reason, _q("-" + pattern)))
    out.append("    ],\n")
    if project["flags"]:
        out.append("    flags = [\n")
        for flag, reason in project["flags"]:
            out.append("        # %s\n        %s,\n" % (reason, _q(flag)))
        out.append("    ],\n")
    if project["bazel"]:
        out.append("    # %s\n    bazel_version = %s,\n" % (project["bazel"][1], _q(project["bazel"][0])))
    if project.get("known_failing"):
        what, reason = project["known_failing"]
        out.append("    # %s\n    known_failing = %s,\n" % (reason, _q(what)))
    if deps:
        out.append("    # Its MODULE.bazel's bazel_deps, dev ones included; tags dep:<module>.\n")
        out.append("    deps = [\n%s    ],\n" % "".join("        %s,\n" % _q(d) for d in deps))
    out.append(")\n")
    return "".join(out)


def build_files(projects, entries):
    """{projects/<module>/BUILD.bazel: its text} for the projects
    projects.json fetches (its `projects` entries).

    Depends only on projects.txt (parsed) and projects.json, so
    tools/generated_test.py can check the committed files without the BCR.
    """
    deps = {e["name"]: sorted(e.get("deps", []) + e.get("dev_deps", [])) for e in entries}
    return {"projects/" + p["name"] + "/BUILD.bazel": render_build(p, deps[p["name"]])
            for p in projects if p["name"] in deps}


def module_mismatch(projects, data):
    """Problems with projects.json against projects.txt: its modules, their
    order, pinned versions and override lines. (What sync gets from the BCR,
    like unpinned versions, isn't checked.)"""
    listed = [p["name"] for p in projects]
    fetched = [e["name"] for e in data["projects"]]
    errors = []
    a = collections.Counter(listed)
    b = collections.Counter(fetched + [s["name"] for s in data["skipped"]])
    if a != b:
        errors.append("projects.json and projects.txt differ on: " + ", ".join(sorted((a - b) + (b - a))))
    if [m for m in fetched if m in a] != [m for m in listed if m in fetched]:
        errors.append("projects.json's projects are not in projects.txt's order")
    by_name = {p["name"]: p for p in projects}
    for e in data["projects"]:
        p = by_name.get(e["name"])
        if not p:
            continue
        if p["version"] and p["version"] != e["version"]:
            errors.append("%s: pinned %s, projects.json has %s" % (p["name"], p["version"], e["version"]))
        if render_append(p["overrides"]) != e["source"].get("module_append", ""):
            errors.append("%s: projects.json's module_append doesn't match its override lines" % p["name"])
        remove = dict(e["source"].get("remove", {}))
        for text in remove.pop("MODULE.bazel", []):
            name = re.search(r"module_name\s*=\s*[\"']([^\"']+)", text)
            if not text.startswith("local_path_override") or not name or name.group(1) not in [
                    m for m, _, _ in p["overrides"]]:
                errors.append("%s: projects.json's MODULE.bazel removals don't match its override lines" % p["name"])
        if rc_remove(p["rc_drop"]) != remove:
            errors.append("%s: projects.json's rc file removals don't match its rc-drop lines" % p["name"])
    for s in data["skipped"]:
        p = by_name.get(s["name"])
        # sync skips a pinned project only for its source type, with a
        # reason naming that version (see source_entry).
        if p and p["version"] and not s["reason"].startswith("%s@%s:" % (p["name"], p["version"])):
            errors.append("%s: pinned %s, but projects.json skips it: %s" % (p["name"], p["version"], s["reason"]))
    return errors


def render_json(commit, entries, skipped, bcr):
    """projects.json: what tools/sources.bzl fetches, the skipped projects,
    and what docs/coverage.md says about the rest of the BCR (see bcr_summary)."""
    return json.dumps({"bcr_commit": commit, "projects": entries, "skipped": skipped, "bcr": bcr},
                      indent=2) + "\n"


# Why a BCR module isn't in the matrix, in docs/coverage.md's order.
UNLISTED = ("deprecated", "git_repository source", "no compatible version", "unlisted")


def unlisted_reason(why, source_type):
    """One of UNLISTED for a module projects.txt doesn't list: why is pick()'s
    reason (None if it picked a version), source_type that version's."""
    if why == "deprecated":
        return "deprecated"
    if why:
        return "no compatible version"
    if source_type not in (None, "archive"):
        return source_type + " source"
    return "unlisted"


def bcr_summary(listed, modules, reasons):
    """projects.json's `bcr`: the number of BCR modules and, per module
    projects.txt doesn't list, why and how many BCR modules depend on it.

    modules maps every BCR module to its latest version's non-dev deps;
    reasons maps each unlisted module to one of UNLISTED.
    """
    dependents = collections.Counter(d for deps in modules.values() for d in set(deps))
    return {"modules": len(modules), "unlisted": [
        {"name": m, "reason": reasons[m], "dependents": dependents[m]}
        for m in sorted(modules) if m not in listed]}


def render_coverage(projects, data, top=50):
    """docs/coverage.md, from projects.txt (parsed) and projects.json only,
    so tools/generated_test.py can check it without the BCR."""
    bcr = data["bcr"]
    kf = {p["name"]: p["known_failing"][0] for p in projects if p.get("known_failing")}
    run = [e["name"] for e in data["projects"]]
    why = collections.Counter(u["reason"] for u in bcr["unlisted"])
    rows = [("BCR modules", bcr["modules"]),
            ("listed in projects.txt", len(projects)),
            ("&nbsp;&nbsp;run (a generated package)", len(run)),
            ("&nbsp;&nbsp;&nbsp;&nbsp;known-failing build", sum(kf.get(n) == "build" for n in run)),
            ("&nbsp;&nbsp;&nbsp;&nbsp;known-failing test", sum(kf.get(n) == "test" for n in run)),
            ("&nbsp;&nbsp;skipped by sync (see projects.json)", len(data["skipped"])),
            ("not listed", len(bcr["unlisted"]))]
    rows += [("&nbsp;&nbsp;" + r, why[r]) for r in UNLISTED]
    out = ["<!-- Generated by tools/sync.py from projects.txt and projects.json. Do not edit. -->\n",
           "# Coverage\n\n",
           "Of the BCR at %s.\n\n" % data["bcr_commit"][:12],
           "| | modules |\n|---|---:|\n"]
    out += ["| %s | %d |\n" % r for r in rows]

    dependents, dev_only, failing = (collections.Counter() for _ in range(3))
    for e in data["projects"]:
        names = e["deps"] + e["dev_deps"]
        dependents.update(names)
        dev_only.update(e["dev_deps"])
        if kf.get(e["name"]) == "build":
            failing.update(names)
    ranked = sorted(dependents, key=lambda m: (-dependents[m], m))
    out += ["\n## Most depended-on modules\n\n",
            "Modules by the number of matrix projects whose MODULE.bazel `bazel_dep`s them "
            "directly (dev dependencies too: a project runs as the root module). "
            "`tools/run.py test --dep <module>` runs those projects, except the known-failing "
            "build ones. Top %d of %d.\n\n"
            % (min(top, len(ranked)), len(ranked)),
            "| module | dependents | dev-only | known-failing build |\n|---|---:|---:|---:|\n"]
    out += ["| %s | %d | %d | %d |\n" % (m, dependents[m], dev_only[m], failing[m]) for m in ranked[:top]]

    unlisted = sorted(bcr["unlisted"], key=lambda u: (-u["dependents"], u["name"]))
    out += ["\n## Unlisted BCR modules\n\n",
            "Candidates to add, by the number of BCR modules whose latest version "
            "depends on them (dev dependencies not counted). Top %d of %d.\n\n"
            % (min(top, len(unlisted)), len(unlisted)),
            "| module | BCR dependents | why not listed |\n|---|---:|---|\n"]
    out += ["| %s | %d | %s |\n" % (u["name"], u["dependents"], u["reason"]) for u in unlisted[:top]]
    return "".join(out)


def counts(projects, skipped):
    """The numbers sync prints."""
    kf = [p["known_failing"][0] for p in projects if p.get("known_failing")]
    return {
        "projects": len(projects),
        "known_failing_build": kf.count("build"),
        "known_failing_test": kf.count("test"),
        "exclusions": sum(len(p["exclude"]) for p in projects),
        "flags": sum(len(p["flags"]) for p in projects),
        "overrides": sum(len(p.get("overrides", [])) for p in projects),
        "rc_drops": sum(len(p.get("rc_drop", [])) for p in projects),
        "skipped": len(skipped),
    }


def status_line(c):
    return ("%(projects)d projects: %(known_failing_build)d known-failing build, "
            "%(known_failing_test)d known-failing test, %(exclusions)d target exclusions, "
            "%(flags)d extra flags, %(overrides)d module overrides, %(rc_drops)d rc drops, "
            "%(skipped)d skipped by sync" % c)


def default_inner_bazel(versions_bzl):
    m = re.search(r'^DEFAULT_INNER_BAZEL = "([^"]+)"', versions_bzl, re.M)
    if not m:
        raise ValueError("tools/versions.bzl sets no DEFAULT_INNER_BAZEL")
    return m.group(1)


